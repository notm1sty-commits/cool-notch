import AppKit
import Observation

/// История текстового буфера обмена (только в памяти, пароли пропускаем).
@MainActor
@Observable
final class ClipboardService {
    struct Entry: Identifiable, Equatable {
        let id = UUID()
        let text: String
        let date: Date
        let appName: String?
    }

    private(set) var entries: [Entry] = []
    private(set) var isEnabled = true

    private let pasteboard = NSPasteboard.general
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private var timer: Timer?
    private let limit = 30

    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init() {
        lastChangeCount = pasteboard.changeCount
        isEnabled = Pref.bool(Pref.clipboardHistory)
        if isEnabled { capture() }
        // Проверка буфера — это одно чтение счётчика, но всё равно делаем её редко и с допуском.
        timer = Timer.coalesced(interval: 1.0, tolerance: 0.4) { [weak self] in
            self?.poll()
        }
    }

    func copy(_ entry: Entry) {
        pasteboard.clearContents()
        pasteboard.setString(entry.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        entries.removeAll { $0.id == entry.id }
        entries.insert(Entry(text: entry.text, date: Date(), appName: entry.appName), at: 0)
    }

    func remove(_ entry: Entry) {
        entries.removeAll { $0.id == entry.id }
    }

    func clear() {
        entries.removeAll()
    }

    private func poll() {
        guard !SystemState.screensAsleep else { return }
        let enabled = Pref.bool(Pref.clipboardHistory)
        if enabled != isEnabled {
            isEnabled = enabled
            if !enabled { entries.removeAll() }
        }
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        if enabled { capture() }
    }

    private func capture() {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        entries.removeAll { $0.text == text }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        entries.insert(Entry(text: text, date: Date(), appName: app), at: 0)
        if entries.count > limit { entries.removeLast(entries.count - limit) }
    }
}
